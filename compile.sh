#!/usr/bin/env bash
# Regenerate firmware/webui.h from web/index.html and compile for the Adafruit KB2040.
# Artifacts (.uf2, .bin, .elf, .map) land in ./build/.
set -euo pipefail
cd "$(dirname "$0")"

CLI=./.arduino/bin/arduino-cli
CFG=./.arduino/arduino-cli.yaml
FQBN=${FQBN:-rp2040:rp2040:adafruit_kb2040:flash=8388608_4194304}   # 8 MB = 4 MB sketch + 4 MB LittleFS

[ -x "$CLI" ] || { echo "arduino-cli missing in ./.arduino/bin (see README: Toolchain bootstrap)"; exit 1; }

# --- embed the Web UI (single source of truth: web/index.html) -----------------
if grep -q ')WEBUI"' web/index.html; then
  echo "web/index.html contains the raw-string delimiter )WEBUI\" - rename it"; exit 1
fi
{
  echo '// AUTO-GENERATED by compile.sh from web/index.html - do not edit by hand.'
  echo '#pragma once'
  echo '#include <Arduino.h>'
  printf 'static const char WEBUI_HTML[] PROGMEM = R"WEBUI('
  cat web/index.html
  echo ')WEBUI";'
  echo 'static const size_t WEBUI_HTML_LEN = sizeof(WEBUI_HTML) - 1;'
} > firmware/webui.h.tmp
mv firmware/webui.h.tmp firmware/webui.h
echo "webui.h: $(wc -c < web/index.html | tr -d ' ') bytes of HTML embedded"

# --- embed the manifest + icons, so "Add to Home Screen" from the board's own page gets them ----
python3 - firmware/webassets.h <<'PY'
import sys
from pathlib import Path
assets = [("manifest.webmanifest", "application/manifest+json"), ("icon-192.png", "image/png"),
          ("icon-512.png", "image/png"), ("icon-maskable-512.png", "image/png"),
          ("apple-touch-icon.png", "image/png")]
out = ["// AUTO-GENERATED by compile.sh from web/ - do not edit by hand.", "#pragma once",
       "#include <Arduino.h>", "#include \"app_types.h\""]
table, total = [], 0
for i, (name, ctype) in enumerate(assets):
    data = Path("web", name).read_bytes()
    total += len(data)
    body = ",".join(str(b) for b in data)
    out.append(f"static const uint8_t WEBASSET_{i}[] PROGMEM = {{{body}}};")
    table.append(f'  {{"/{name}", "{ctype}", WEBASSET_{i}, sizeof(WEBASSET_{i})}},')
out += ["static const WebAsset WEB_ASSETS[] = {", *table, "};"]
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
print(f"webassets.h: {len(assets)} files, {total} bytes embedded")
PY

# --- per-build stamp: changes every run so firmware.ino recompiles and __DATE__/__TIME__
#     (the "version" in telemetry) always identify this exact build ---------------
# NCM_TEST=1: Android test build (NCM-only USB, MAC first byte 0x00), see FW_NCM_TEST in firmware.ino.
printf '#pragma once\n#define FW_BUILD_ID "%s"\n#define FW_NCM_TEST %s\n' \
  "$(date +%Y%m%d-%H%M%S)-$$" "${NCM_TEST:-0}" > firmware/build_info.h
if [ "${NCM_TEST:-0}" = 1 ]; then echo "NOTE: NCM_TEST=1 test build (no USB serial, MAC 00:...)"; fi

# --- compile -----------------------------------------------------------------
mkdir -p build
"$CLI" --config-file "$CFG" compile \
  --fqbn "$FQBN" \
  --warnings default \
  --output-dir ./build \
  "$@" \
  ./firmware

ls -l build/firmware.ino.uf2 build/firmware.ino.bin
